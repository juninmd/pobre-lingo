import { AlertCircle, CheckCircle2, Volume2 } from "lucide-react";
import { useMemo, useState } from "react";
import { useNavigate, useSearchParams } from "react-router-dom";
import { LessonCompleteModal } from "@/components/curriculum/LessonCompleteModal";
import { LessonProgressBar } from "@/components/curriculum/LessonProgressBar";
import { Button } from "@/components/ui/button";
import {
	Card,
	CardContent,
	CardDescription,
	CardFooter,
	CardHeader,
	CardTitle,
} from "@/components/ui/card";
import { useToast } from "@/hooks/use-toast";
import { useCurriculumProgress } from "@/hooks/useCurriculumProgress";
import { getListeningExercisesForLesson } from "@/lib/exerciseData";
import { tts } from "@/lib/tts";

export function ListeningExercise() {
	const [searchParams] = useSearchParams();
	// Match the query params generated by getLessonLink in routes.ts
	const moduleId =
		searchParams.get("module") ?? searchParams.get("moduleId") ?? undefined;
	const lessonId =
		searchParams.get("lesson") ?? searchParams.get("lessonId") ?? undefined;
	const navigate = useNavigate();
	const { completeLesson } = useCurriculumProgress();
	const { toast } = useToast();

	const exercises = useMemo(() => {
		return lessonId ? getListeningExercisesForLesson(lessonId) : [];
	}, [lessonId]);

	const [currentIndex, setCurrentIndex] = useState(0);
	const [selectedOption, setSelectedOption] = useState<string | null>(null);
	const [isCorrect, setIsCorrect] = useState<boolean | null>(null);
	const [isLessonFinished, setIsLessonFinished] = useState(false);

	// If no exercises found (shouldn't happen with fallback), show safety
	if (!exercises.length) return <div>Carregando...</div>;

	const currentItem = exercises[currentIndex];

	const handleSpeak = () => {
		tts.speak(currentItem.text, "en-US", 0.8);
	};

	const handleCheck = () => {
		if (selectedOption === currentItem.text) {
			setIsCorrect(true);
			toast({
				title: "Correto!",
				className: "bg-green-500 text-white",
				duration: 1000,
			});
		} else {
			setIsCorrect(false);
			toast({
				title: "Incorreto",
				description: "Tente novamente.",
				variant: "destructive",
			});
		}
	};

	const handleNext = () => {
		if (currentIndex < exercises.length - 1) {
			setCurrentIndex((prev) => prev + 1);
			setSelectedOption(null);
			setIsCorrect(null);
		} else {
			// Complete
			if (moduleId && lessonId) {
				completeLesson(moduleId, lessonId, 100);
			}
			setIsLessonFinished(true);
		}
	};

	const handleContinue = () => {
		navigate("/");
	};

	return (
		<div className="max-w-2xl mx-auto p-4 space-y-6">
			<LessonCompleteModal
				isOpen={isLessonFinished}
				xpEarned={100}
				onContinue={handleContinue}
			/>

			{/* Barra de Progresso da Jornada */}
			{moduleId && lessonId && (
				<LessonProgressBar
					moduleId={moduleId}
					lessonId={lessonId}
					showCompleteButton={false}
					className="mb-6"
				/>
			)}

			<Card>
				<CardHeader>
					<CardTitle className="flex items-center gap-2">
						<Volume2 className="h-6 w-6 text-primary" /> Exercício de Escuta
					</CardTitle>
					<CardDescription>
						Ouça a frase e selecione a opção correta.
					</CardDescription>
				</CardHeader>
				<CardContent className="space-y-6">
					{/* Progress bar specific to this exercise session */}
					<div className="w-full bg-secondary h-2 rounded-full overflow-hidden">
						<div
							className="bg-primary h-full transition-all duration-300"
							style={{ width: `${(currentIndex / exercises.length) * 100}%` }}
						/>
					</div>

					<div className="flex justify-center py-8">
						<Button
							size="lg"
							className="h-24 w-24 rounded-full shadow-lg hover:scale-105 transition-transform"
							onClick={handleSpeak}
						>
							<Volume2 className="h-10 w-10" />
						</Button>
					</div>

					<div className="space-y-3">
						{currentItem.options.map((option, idx) => (
							<div
								key={idx}
								className={`p-4 border-2 rounded-xl cursor-pointer transition-all font-medium ${
									selectedOption === option
										? "border-primary bg-primary/5 shadow-md"
										: "border-muted hover:border-primary/50 hover:bg-accent"
								}`}
								onClick={() => !isCorrect && setSelectedOption(option)}
							>
								{option}
							</div>
						))}
					</div>

					{isCorrect !== null && (
						<div
							className={`p-4 rounded-lg flex items-center gap-2 animate-in fade-in slide-in-from-bottom-2 ${isCorrect ? "bg-green-100 text-green-800 dark:bg-green-900/30 dark:text-green-400" : "bg-red-100 text-red-800 dark:bg-red-900/30 dark:text-red-400"}`}
						>
							{isCorrect ? (
								<CheckCircle2 className="h-5 w-5" />
							) : (
								<AlertCircle className="h-5 w-5" />
							)}
							<p>
								{isCorrect ? "Muito bem! Você acertou." : "Não foi dessa vez."}
							</p>
						</div>
					)}
				</CardContent>
				<CardFooter className="justify-between pt-6 border-t">
					<Button variant="ghost" disabled>
						Pular
					</Button>
					{isCorrect ? (
						<Button
							onClick={handleNext}
							className="w-32 font-bold animate-bounce-short"
						>
							Próximo
						</Button>
					) : (
						<Button
							onClick={handleCheck}
							disabled={!selectedOption}
							className="w-32 font-bold"
						>
							Verificar
						</Button>
					)}
				</CardFooter>
			</Card>
		</div>
	);
}
